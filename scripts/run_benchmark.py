def curation_summary(
    raw_rows: int,
    valid: pd.DataFrame,
    clean: pd.DataFrame,
    label_col: str = "Y",
) -> dict:
    if valid.empty:
        conflicting_groups = 0
        conflicting_rows = 0
        unique_canonical = 0
    else:
        grouped = valid.groupby("Drug")[label_col]
        conflicts = grouped.nunique(dropna=False)
        conflict_smiles = set(conflicts[conflicts > 1].index)
        conflicting_groups = int(len(conflict_smiles))
        conflicting_rows = int(valid["Drug"].isin(conflict_smiles).sum())
        unique_canonical = int(valid["Drug"].nunique())
    return {
        "raw_rows": int(raw_rows),
        "valid_smiles": int(len(valid)),
        "unique_canonical_smiles": unique_canonical,
        "duplicate_rows": int(max(0, len(valid) - unique_canonical)),
        "conflicting_label_groups": conflicting_groups,
        "conflicting_rows_removed": conflicting_rows,
        "duplicate_rows_collapsed": int(max(0, len(valid) - conflicting_rows - len(clean))),
        "final_n": int(len(clean)),
        "deduplication_policy": "canonical-SMILES groups with conflicting binary labels removed; non-conflicting duplicate groups collapsed to the first row",
        "standardization_policy": "RDKit canonical SMILES only; no salt stripping, neutralization, or tautomer canonicalization",
    }


def curate_binary_rows(raw: pd.DataFrame, smiles_col: str, label_col: str) -> tuple[pd.DataFrame, dict]:
    work = raw[[smiles_col, label_col]].copy()
    work["original_index"] = work.index.to_numpy(dtype=int)
    work = work.dropna(subset=[smiles_col, label_col])
    work["Drug"] = work[smiles_col].map(canonicalize_smiles)
    work = work.dropna(subset=["Drug"])
    work["Y"] = work[label_col].astype(int)
    valid = work[["Drug", "Y", "original_index"]].copy()

    label_counts = valid.groupby("Drug")["Y"].nunique(dropna=False)
    conflicting = set(label_counts[label_counts > 1].index)
    clean = valid[~valid["Drug"].isin(conflicting)].drop_duplicates("Drug", keep="first").reset_index(drop=True)
    summary = curation_summary(len(raw), valid, clean, label_col="Y")
    return clean, summary


def load_binary_tab(data_root: Path, filename: str, name: str, embedding_bundle: str | None) -> DatasetBundle:
    raw = pd.read_csv(data_root / filename, sep="\t")
    df, summary = curate_binary_rows(raw, "Drug", "Y")
    y = df["Y"].astype(int).to_numpy()
    return DatasetBundle(
        name=name,
        source=filename,
        smiles=df["Drug"].to_numpy(dtype=object),
        y=y,
        embedding_bundle=embedding_bundle,
        embedding_indices=df["original_index"].to_numpy(dtype=int),
        curation=summary,
    )


def load_chembl_cns_tasks(data_root: Path, threshold: float = 6.5) -> list[DatasetBundle]:
    path = data_root / "chembl_cns_targets.csv"
    if not path.exists():
        return []
    raw = pd.read_csv(path)
    df = raw.dropna(subset=["canonical_smiles", "pchembl_value", "target_chembl_id"]).copy()
    df["original_index"] = df.index.to_numpy(dtype=int)
    df["canonical_smiles"] = df["canonical_smiles"].map(canonicalize_smiles)
    df = df.dropna(subset=["canonical_smiles"])
    tasks: list[DatasetBundle] = []
    for target, sub in df.groupby("target_chembl_id", sort=True):
        task = pd.DataFrame(
            {
                "Drug": sub["canonical_smiles"].to_numpy(dtype=object),
                "Y": (sub["pchembl_value"].astype(float).to_numpy() >= threshold).astype(int),
                "original_index": sub["original_index"].to_numpy(dtype=int),
            }
        )
        label_counts = task.groupby("Drug")["Y"].nunique(dropna=False)
        conflicting = set(label_counts[label_counts > 1].index)
        clean = task[~task["Drug"].isin(conflicting)].drop_duplicates("Drug", keep="first").reset_index(drop=True)
        summary = curation_summary(int((raw["target_chembl_id"] == target).sum()), task, clean, label_col="Y")
        y = clean["Y"].astype(int).to_numpy()
        if len(np.unique(y)) < 2:
            continue
        target_name = str(sub["target_pref_name"].iloc[0]).replace(" ", "_")
        target_name = "".join(c if c.isalnum() or c == "_" else "" for c in target_name)[:32]
        tasks.append(
            DatasetBundle(
                name=f"ChEMBL_CNS_{target}_{target_name}",
                source=f"chembl_cns_targets.csv:pChEMBL>={threshold}",
                smiles=clean["Drug"].to_numpy(dtype=object),
                y=y,
                embedding_bundle="ChEMBL_CNS_targets",
                embedding_indices=clean["original_index"].to_numpy(dtype=int),
                curation=summary,
            )
        )
    return tasks


def load_local_datasets(data_root: Path, include_chembl: bool = True) -> list[DatasetBundle]:
    specs = [
        ("bbb_martins.tab", "BBB_Martins", "BBB_Martins"),
        ("b3db_classification.tab", "B3DB_Classification", "B3DB_Classification"),
        ("hia_hou.tab", "HIA_Hou", "HIA_Hou"),
        ("bioavailability_ma.tab", "Bioavailability_Ma", "Bioavailability_Ma"),
        ("pampa_ncats.tab", "PAMPA_NCATS", "PAMPA_NCATS"),
    ]
    datasets: list[DatasetBundle] = []
    for filename, name, embedding_bundle in specs:
        if (data_root / filename).exists():
            ds = load_binary_tab(data_root, filename, name, embedding_bundle)
            if len(np.unique(ds.y)) == 2:
                datasets.append(ds)
    if include_chembl:
        datasets.extend(load_chembl_cns_tasks(data_root))
    return datasets


def morgan_features(smiles: Iterable[str], n_bits: int = 1024, radius: int = 2) -> tuple[np.ndarray, np.ndarray]:
    gen = rdFingerprintGenerator.GetMorganGenerator(radius=radius, fpSize=n_bits)
    rows: list[np.ndarray] = []
    valid: list[int] = []
    for i, smi in enumerate(smiles):
        mol = Chem.MolFromSmiles(str(smi))
        if mol is None:
            continue
        arr = np.zeros((n_bits,), dtype=np.float32)
        fp = gen.GetFingerprint(mol)
        DataStructs.ConvertToNumpyArray(fp, arr)
        rows.append(arr)
        valid.append(i)
    if not rows:
        return np.empty((0, n_bits), dtype=np.float32), np.array([], dtype=int)
    return np.vstack(rows), np.array(valid, dtype=int)


def rdkit_descriptor_features(smiles: Iterable[str]) -> tuple[np.ndarray, np.ndarray]:
    rows: list[list[float]] = []
    valid: list[int] = []
    for i, smi in enumerate(smiles):
        mol = Chem.MolFromSmiles(str(smi))
        if mol is None:
            continue
        vals: list[float] = []
        ok = True
        for _, fn in DESCRIPTOR_FNS:
            try:
                val = float(fn(mol))
            except Exception:
                ok = False
                break
            if not math.isfinite(val):
                ok = False
                break
            vals.append(val)
        if ok:
            rows.append(vals)
            valid.append(i)
    if not rows:
        return np.empty((0, len(DESCRIPTOR_FNS)), dtype=np.float32), np.array([], dtype=int)
    return np.asarray(rows, dtype=np.float32), np.array(valid, dtype=int)


def load_embeddings(
    data_root: Path,
    dataset: DatasetBundle,
    key: str,
    valid_indices: np.ndarray,
) -> np.ndarray | None:
    if dataset.embedding_bundle is None:
        return None
    filename = EMBEDDING_FILES.get(dataset.embedding_bundle, {}).get(key)
    if not filename:
        return None
    path = data_root / filename
    if not path.exists():
        return None
    emb = np.load(path)
    if dataset.embedding_indices is not None:
        emb = emb[dataset.embedding_indices]
    if len(emb) != len(dataset.smiles):
        raise ValueError(
            f"Embedding length mismatch for {dataset.name}/{key}: {len(emb)} vs {len(dataset.smiles)}"
        )
    return emb[valid_indices].astype(np.float32, copy=False)


def build_features(data_root: Path, dataset: DatasetBundle) -> FeatureBundle:
    x_morgan, valid_morgan = morgan_features(dataset.smiles)
    x_desc, valid_desc = rdkit_descriptor_features(dataset.smiles)
    valid_indices = np.intersect1d(valid_morgan, valid_desc)
    if len(valid_indices) != len(dataset.smiles):
        # Keep all representations aligned after dropping invalid molecules.
        valid_set = set(int(i) for i in valid_indices)
        morgan_mask = np.array([int(i) in valid_set for i in valid_morgan])
        desc_mask = np.array([int(i) in valid_set for i in valid_desc])
        x_morgan = x_morgan[morgan_mask]
        x_desc = x_desc[desc_mask]

    features = {
        "morgan": x_morgan,
        "rdkit": x_desc,
    }
    for emb_key in ("chemberta", "molformer"):
        emb = load_embeddings(data_root, dataset, emb_key, valid_indices)
        if emb is not None:
            features[emb_key] = emb
    return FeatureBundle(dataset=dataset, features=features, valid_indices=valid_indices)


def molecule_scaffold(smiles: str) -> str:
    mol = Chem.MolFromSmiles(str(smiles))
    if mol is None:
        return str(smiles)
    scaffold = MurckoScaffold.MurckoScaffoldSmiles(mol=mol, includeChirality=False)
    return scaffold or Chem.MolToSmiles(mol, canonical=True)


def random_split(y: np.ndarray, seed: int, test_size: float = 0.2) -> tuple[np.ndarray, np.ndarray, str]:
    splitter = StratifiedShuffleSplit(n_splits=1, test_size=test_size, random_state=seed)
    train_idx, test_idx = next(splitter.split(np.zeros_like(y), y))
    return train_idx, test_idx, ""


def scaffold_split(smiles: np.ndarray, y: np.ndarray, seed: int, test_fraction: float = 0.2) -> tuple[np.ndarray, np.ndarray, str]:
    groups: dict[str, list[int]] = {}
    for i, smi in enumerate(smiles):
        groups.setdefault(molecule_scaffold(str(smi)), []).append(i)
    rng = np.random.default_rng(seed)
    scaffold_groups = list(groups.values())

    target_test = max(1, int(round(len(y) * test_fraction)))
    best: tuple[float, np.ndarray, np.ndarray] | None = None
    for _ in range(256):
        order = list(scaffold_groups)
        rng.shuffle(order)
        test: list[int] = []
        train: list[int] = []
        for group in order:
            if len(test) < target_test:
                test.extend(group)
            else:
                train.extend(group)
        train_idx = np.asarray(sorted(train), dtype=int)
        test_idx = np.asarray(sorted(test), dtype=int)
        if len(train_idx) == 0 or len(test_idx) == 0:
            continue
        if len(np.unique(y[train_idx])) < 2 or len(np.unique(y[test_idx])) < 2:
            continue
        size_penalty = abs(len(test_idx) - target_test) / max(1, len(y))
        balance_penalty = abs(float(np.mean(y[test_idx])) - float(np.mean(y)))
        score = size_penalty + balance_penalty
        if best is None or score < best[0]:
            best = (score, train_idx, test_idx)

    warning = ""
    if best is None:
        train_idx, test_idx, _ = random_split(y, seed, test_fraction)
        warning = "scaffold split had a single class; fell back to stratified random"
    else:
        _, train_idx, test_idx = best
    return train_idx, test_idx, warning


def stratified_subsample(train_idx: np.ndarray, y: np.ndarray, n: int, seed: int, min_class_count: int = 5) -> np.ndarray | None:
    if len(train_idx) < n:
        return None
    rng = np.random.default_rng(seed)
    y_train = y[train_idx]
    classes, counts = np.unique(y_train, return_counts=True)
    if len(classes) < 2:
        return None
    if np.any(counts < min_class_count):
        return None
    desired: dict[int, int] = {}
    remaining = n
    for cls, count in zip(classes, counts):
        quota = max(min_class_count, int(round(n * (count / len(train_idx)))))
        quota = min(quota, int(count))
        desired[int(cls)] = quota
        remaining -= quota
    while remaining > 0:
        candidates = [int(c) for c in classes if desired[int(c)] < int(counts[np.where(classes == c)[0][0]])]
        if not candidates:
            break
        chosen = candidates[int(rng.integers(0, len(candidates)))]
        desired[chosen] += 1
        remaining -= 1
    selected: list[int] = []
    for cls in classes:
        cls_idx = train_idx[y_train == cls]
        take = desired[int(cls)]
        selected.extend(rng.choice(cls_idx, size=take, replace=False).tolist())
    rng.shuffle(selected)
    out = np.asarray(selected, dtype=int)
    if len(out) < 2 or len(np.unique(y[out])) < 2:
        return None
    return out


def make_model(model_name: str, seed: int, rf_trees: int, xgb_trees: int, n_jobs: int):
    representation, classifier, _ = MODEL_SPECS[model_name]
    if classifier == "rf":
        return RandomForestClassifier(
            n_estimators=rf_trees,
            max_features="sqrt",
            min_samples_leaf=1,
            class_weight="balanced_subsample",
            random_state=seed,
            n_jobs=n_jobs,
        )
    if classifier == "xgb":
        if XGBClassifier is None:
            raise RuntimeError("xgboost is not installed")
        return XGBClassifier(
            n_estimators=xgb_trees,
            max_depth=4,
            learning_rate=0.05,
            subsample=0.85,
            colsample_bytree=0.70,
            objective="binary:logistic",
            eval_metric="logloss",
            tree_method="hist",
            random_state=seed,
            n_jobs=n_jobs,
            verbosity=0,
        )
    if classifier == "lr":
        return make_pipeline(
            StandardScaler(),
            LogisticRegression(
                max_iter=2000,
                class_weight="balanced",
                solver="lbfgs",
                random_state=seed,
            ),
        )
    raise ValueError(f"Unknown classifier for {model_name}: {classifier}")


def predict_positive_probability(model, x_test: np.ndarray) -> np.ndarray:
    if hasattr(model, "predict_proba"):
        probs = model.predict_proba(x_test)
        if probs.shape[1] == 2:
            return probs[:, 1]
    if hasattr(model, "decision_function"):
        scores = model.decision_function(x_test)
        return 1.0 / (1.0 + np.exp(-scores))
    preds = model.predict(x_test)
    return np.asarray(preds, dtype=float)


def expected_calibration_error(y_true: np.ndarray, prob: np.ndarray, bins: int = 10) -> float:
    edges = np.linspace(0.0, 1.0, bins + 1)
    ece = 0.0
    for lo, hi in zip(edges[:-1], edges[1:]):
        if hi == 1.0:
            mask = (prob >= lo) & (prob <= hi)
        else:
            mask = (prob >= lo) & (prob < hi)
        if not np.any(mask):
            continue
        frac_pos = float(np.mean(y_true[mask]))
        conf = float(np.mean(prob[mask]))
        ece += float(np.mean(mask)) * abs(frac_pos - conf)
    return ece


def metric_or_nan(fn, *args) -> float:
    try:
        val = fn(*args)
    except Exception:
        return float("nan")
    try:
        return float(val)
    except Exception:
        return float("nan")


def evaluate_predictions(y_true: np.ndarray, prob: np.ndarray) -> dict[str, float]:
    pred = (prob >= 0.5).astype(int)
    both_classes = len(np.unique(y_true)) == 2
    metrics = {
        "auroc": metric_or_nan(roc_auc_score, y_true, prob) if both_classes else float("nan"),
        "auprc": metric_or_nan(average_precision_score, y_true, prob) if both_classes else float("nan"),
        "mcc": metric_or_nan(matthews_corrcoef, y_true, pred),
        "f1": metric_or_nan(f1_score, y_true, pred),
        "balanced_accuracy": metric_or_nan(balanced_accuracy_score, y_true, pred),
        "brier": metric_or_nan(brier_score_loss, y_true, prob),
        "log_loss": metric_or_nan(log_loss, y_true, np.c_[1.0 - prob, prob]) if both_classes else float("nan"),
        "ece_10": expected_calibration_error(y_true, prob, bins=10),
    }
    return metrics


def bootstrap_mean_ci(values: np.ndarray, seed: int = 20260512, reps: int = 5000) -> tuple[float, float]:
    values = np.asarray(values, dtype=float)
    values = values[np.isfinite(values)]
    if len(values) == 0:
        return float("nan"), float("nan")
    if len(values) == 1:
        return float(values[0]), float(values[0])
    rng = np.random.default_rng(seed)
    draws = rng.choice(values, size=(reps, len(values)), replace=True).mean(axis=1)
    lo, hi = np.quantile(draws, [0.025, 0.975])
    return float(lo), float(hi)


def bootstrap_cluster_mean_ci(values: np.ndarray, seed: int = 20260512, reps: int = 10000) -> tuple[float, float]:
    return bootstrap_mean_ci(values, seed=seed, reps=reps)


def wilcoxon_pvalue(values: np.ndarray) -> float:
    values = np.asarray(values, dtype=float)
    values = values[np.isfinite(values)]
    if len(values) < 2 or np.allclose(values, 0.0) or stats is None:
        return float("nan")
    try:
        return float(stats.wilcoxon(values, zero_method="wilcox", alternative="two-sided").pvalue)
    except Exception:
        return float("nan")


